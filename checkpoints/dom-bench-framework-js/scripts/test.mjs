import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { browserSession } from './browser.mjs';
const session = await browserSession();
try {
  for (const framework of ['react', 'angular', 'vue', 'svelte']) {
    const page = await session.browser.newPage();
    page.setDefaultTimeout(15000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(`http://127.0.0.1:4173/${framework}.html`);
    await page.waitForFunction(() => Boolean(window.bench));
    assert.equal(await page.locator('.task-row').count(), 8);
    await page.getByRole('textbox', { name: 'Task name', exact: true }).fill('A task to verify');
    await page.getByRole('combobox', { name: 'Task priority', exact: true }).selectOption('High');
    await page.getByRole('button', { name: '+ Add task', exact: true }).click();
    const row = page.locator('.task-row').last();
    await row.locator('input').waitFor();
    assert.equal(await row.locator('input').inputValue(), 'A task to verify');
    await row.locator('input').fill('Edited task');
    await row.locator('select').selectOption('Low');
    await page.waitForFunction(() => window.bench.snapshot().at(-1)?.name === 'Edited task' && window.bench.snapshot().at(-1)?.priority === 'Low');
    await row.getByRole('button').click();
    assert.equal(await page.locator('.task-row').count(), 8);
    await page.getByRole('textbox', { name: 'Task name', exact: true }).fill('   ');
    await page.getByRole('button', { name: '+ Add task', exact: true }).click();
    assert.equal(await page.locator('.task-row').count(), 8);
    await page.evaluate(async () => { const { makeTasks } = await import('/runner.js'); await window.bench.replace(makeTasks(1000)); });
    assert.equal(await page.locator('.task-row').count(), 1000);
    const result = await page.evaluate(async () => { const { runFramework } = await import('/runner.js'); return runFramework(window, { samples: 1, warmups: 0 }); });
    assert.equal(Object.keys(result).length, 5);
    await page.evaluate(() => window.bench.replace([]));
    await page.getByText('All clear. Add a task to get started.').waitFor();
    assert.deepEqual(errors, []);
    console.log(`PASS ${framework}: add, edit name/priority, delete, validation, 1,000 rows, all benchmark cases, empty state`);
    await page.close();
  }
  const page = await session.browser.newPage({ viewport: { width: 1440, height: 1100 } });
  await page.goto('http://127.0.0.1:4173');
  await page.getByRole('heading', { name: 'The framework lineup' }).waitFor();
  await page.locator('[data-view="results"]').click();
  await page.getByRole('heading', { name: 'The numbers behind the DOM' }).waitFor();
  await page.locator('[data-dialog="methodology"]').first().click();
  await page.getByRole('heading', { name: 'A fair test starts with the setup.' }).waitFor();
  await page.getByRole('button', { name: 'Close methodology' }).click();
  await page.locator('[data-view="playground"]').click();
  await page.locator('[data-framework="svelte"]').click();
  await page.frameLocator('#playground').getByRole('button', { name: '+ Add task' }).waitFor();
  await page.locator('#seed-tasks').click();
  await page.waitForFunction(() => document.querySelector('#playground').contentDocument.querySelectorAll('.task-row').length === 100);
  await page.locator('#clear-tasks').click();
  await page.frameLocator('#playground').getByText('All clear. Add a task to get started.').waitFor();
  await page.locator('[data-view="overview"]').click();
  await page.locator('.run-button').click();
  await page.waitForFunction(() => /Benchmark complete\.|Benchmark stopped:/.test(document.querySelector('#status').textContent), null, { timeout: 180000 });
  assert.match(await page.getByRole('status').innerText(), /Benchmark complete\./);
  assert.equal(await page.locator('.chart-row').count(), 4);
  await page.locator('#chart-operation').selectOption('update50');
  assert.equal(await page.locator('.chart-row').count(), 4);
  await page.locator('[data-view="results"]').click();
  assert.equal(await page.locator('#results-body tr').count(), 4);
  const downloadPromise = page.waitForEvent('download');
  await page.locator('.export-button').click();
  const download = await downloadPromise;
  const stream = await download.createReadStream();
  let csv = ''; for await (const chunk of stream) csv += chunk;
  assert.equal(csv.trim().split('\r\n').length, 21);
  assert.match(csv, /Measured in your browser/);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('dom-bench-results-v1')));
  assert.equal(Object.keys(saved.frameworks).length, 4);
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#results-meta').textContent.includes('Measured in your browser'));
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('dom-bench-results-v1'))), saved);
  for (const [index, framework] of ['react', 'angular', 'vue', 'svelte'].entries()) {
    assert.match(await page.locator('#results-body tr').nth(index).innerText(), new RegExp(saved.frameworks[framework].render1000.median.toFixed(2).replace('.', '\\.')));
  }
  await page.locator('[data-view="overview"]').click();
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/dashboard-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Mobile page must not overflow horizontally');
  await page.screenshot({ path: 'artifacts/dashboard-mobile.png', fullPage: true });
  console.log('PASS dashboard: navigation, modal, framework switching, sample loading, clearing, full benchmark run, chart selection, CSV export, persistence, responsive width');
} finally { await session.close(); }
